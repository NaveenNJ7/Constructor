package Constructoroverloading;

public class Theory {

	
	/*
	  Constructor overloading
	  process of having multiple constructors in a same class but
	  difference in arguments is called constructor overloading
	  To achieve overloading we need to follow either of the following rules
	  
	  1) There should be change in the number of arguments
	  2) There should be change in Data type of arguments
	  3) There should be change in sequence or order of Data type
	  
	  
	 one object can invoke only one constructor at a time
	 */
}
