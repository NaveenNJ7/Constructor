	/*
	  Constructor - 
	  			   set of instructions used to initialization(Assigning) and 
	  			   instantiation (object creation)
	  	syntax 
	  	       Access specifier constructor name(optionally arguments)
	  	       {
	  	       
	  	       }
	  	       
	  	      1) Class name and constructor name should be same
	  	      2) it does not have any return type
	  	      3) It will get executed during object creation
	  	      
	  	      Two types
	  	       Default constructor
	  	         if user not defined any constructor explicitly in the class, 
	  	         then compiler automatically generate constructor.
	             it will not accept any arguments and does not have any implementations or statements
	          
	          Custom constructor or user defined constructor
	          if a constructor explicitly defined inside a class by user then it is custom constructor
	          
	          two types
	          1) Parameterized custom constructor 
	          2) Non parameterized custom con
	          
	          Note - if there is defined constructor or custom cons present in class, 
	          there can not be default con present VICE VERSA
	          
	          
	          
	 */

